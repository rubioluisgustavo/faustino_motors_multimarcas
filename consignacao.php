(function () {
    const form = document.getElementById('formConsignacao');
    const phone = '5514997533055';

    function digits(value) {
        return value.replace(/\D/g, '');
    }

    function mask(input) {
        const type = input.dataset.mask;
        let value = digits(input.value);

        if (type === 'phone') {
            value = value.slice(0, 11);
            if (value.length > 2) {
                const areaCode = value.slice(0, 2);
                const number = value.slice(2);
                const prefixLength = number.charAt(0) === '9' ? 5 : 4;
                value = '(' + areaCode + ') ' + number.slice(0, prefixLength)
                    + (number.length > prefixLength ? '-' + number.slice(prefixLength) : '');
            }
        }

        if (type === 'kilometers') {
            value = value.replace(/\B(?=(\d{3})+(?!\d))/g, '.');
        }

        if (type === 'money' && value) {
            value = 'R$ ' + (Number(value) / 100).toLocaleString('pt-BR', { minimumFractionDigits: 2 });
        }

        input.value = value;
    }

    form.querySelectorAll('[data-mask]').forEach(input => {
        input.addEventListener('input', () => mask(input));
    });

    form.addEventListener('submit', event => {
        event.preventDefault();
        const data = new FormData(form);
        const fields = [
            ['nome', 'Nome'],
            ['whatsapp', 'WhatsApp'],
            ['cidade', 'Cidade'],
            ['veiculo', 'Marca e modelo'],
            ['ano', 'Ano de fabricação / modelo'],
            ['quilometragem', 'Quilometragem'],
            ['valor', 'Quanto pretende receber?']
        ];
        let message = 'Olá! Gostaria de consignar meu carro com a Faustino Motors e solicitar uma avaliação.\n\n';

        fields.forEach(([key, label]) => {
            message += '*' + label + ':* ' + data.get(key) + '\n';
        });

        window.open('https://wa.me/' + phone + '?text=' + encodeURIComponent(message), '_blank', 'noopener,noreferrer');
    });
}());
</script>
